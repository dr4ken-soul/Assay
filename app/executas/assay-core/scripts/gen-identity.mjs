/**
 * Generates the identity module the plugin compiles against.
 *
 * The plugin reports a tool id and a version. Both used to be read from
 * `executa.json` and `package.json` at startup, which is right for a source
 * checkout but impossible for a single executable application: a binary has
 * no files beside it to read.
 *
 * So the two values are generated into a module and compiled in. The
 * generator reads the same two files the CLI reads, so there is still one
 * source of truth, and the contract test asserts the built plugin agrees
 * with the files on disk.
 *
 * Usage:
 *   node scripts/gen-identity.mjs
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

/** The project root, one level above this script. */
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')

/** Where the generated module is written. */
const TARGET = join(ROOT, 'src', 'generated-identity.ts')

const executa = JSON.parse(readFileSync(join(ROOT, 'executa.json'), 'utf8'))
const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'))

if (typeof executa.tool_id !== 'string' || !executa.tool_id.startsWith('tool-')) {
  throw new Error(`executa.json has no minted tool_id, got ${JSON.stringify(executa.tool_id)}`)
}
if (typeof executa.version !== 'string' || executa.version.length === 0) {
  throw new Error('executa.json has no version')
}
if (typeof pkg.version !== 'string' || pkg.version.length === 0) {
  throw new Error('package.json has no version')
}
if (executa.version !== pkg.version) {
  throw new Error(`version drift: executa.json says ${executa.version}, package.json says ${pkg.version}`)
}

const contents = `/**
 * The tool id and version, generated by scripts/gen-identity.mjs.
 *
 * Do not edit. The generator reads executa.json and package.json, so the
 * tool id the platform minted and the version the platform froze are the
 * same two strings the CLI publishes from.
 */

/** The server-minted tool id. */
export const TOOL_ID = ${JSON.stringify(executa.tool_id)}

/** The plugin version. */
export const VERSION = ${JSON.stringify(pkg.version)}
`

mkdirSync(dirname(TARGET), { recursive: true })
writeFileSync(TARGET, contents, 'utf8')
process.stdout.write(`generated identity ${executa.tool_id} ${executa.version}\n`)
